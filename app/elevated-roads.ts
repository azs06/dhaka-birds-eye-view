/**
 * ELEVATED ROADS: flyovers, expressway viaducts and river bridges that are too
 * long for a point landmark with a clearing radius. This file is the data
 * table plus the pure (three.js-free) layout and clearance maths; the meshes
 * are built by `buildElevatedRoads` in BirdFlight.tsx.
 *
 * TABLE FORMAT (one entry per structure)
 *   key            stable id, also the mesh name prefix.
 *   label          English name on the floating label; add its Bangla name to
 *                  PLACE_NAMES_BN in i18n.ts. Omit for no label.
 *   style          "flyover" (round piers with hammerheads), "viaduct" (the
 *                  same, heavier) or "river-bridge" (blade piers under a
 *                  crosshead, on pile caps in the river; darker solid
 *                  parapets, no open railings). See
 *                  ELEVATED_ROAD_STYLES for what each one changes.
 *   deckHalfWidth  half the deck width in metres, parapets included.
 *   depth          girder depth below the road surface.
 *   pierSpacing    metres between piers along each chain.
 *   replacesWayIds OSM way ids this structure stands in for. They are dropped
 *                  from the flat ground-road mesh and from ground traffic (by
 *                  id, in every data source). List only the elevated ways,
 *                  never the street running underneath.
 *   trimsWayIds    ways that carry on beyond the structure (a highway whose
 *                  last 150 m is the bridge approach): only the part under a
 *                  deck is dropped, cut by geometry against the chains.
 *   collide        false leaves the deck out of bird collision (default true).
 *   haunch         extra girder depth at the piers of a chain's mainSpan.
 *   lanes          lane count: lanes - 1 lane lines across the deck (default 2).
 *   lampSpacing    metres between lamp posts along each parapet (default none).
 *   labelAt        distance along chain 0 where the label floats (default its
 *                  middle).
 *   chains         one per carriageway or ramp, each drawn as its own deck:
 *     points       [lat, lon] centreline in the direction of travel, simplified
 *                  to about 1.5 m. Never join two carriageways into one chain.
 *     heights      [distance along the chain in metres, road surface height]
 *                  keys, straight grades between. A negative distance counts
 *                  back from the far end and Infinity is the far end itself.
 *                  Land a free end at ELEVATED_ROAD_GROUND (the ground-road
 *                  surface); end a chain that joins another deck at that
 *                  deck's height, on that deck's centreline.
 *     halfWidth    this chain's half width where it differs from the
 *                  structure's deckHalfWidth (ramps are narrower).
 *     lanes        this chain's lane count where it differs from the
 *                  structure's (a single-lane ramp off a four-lane bridge).
 *     twoWay       true where one chain carries both directions (a river
 *                  bridge drawn as the midline of its pair); chains are
 *                  one-way, in the order of their points, by default. Used
 *                  by the deck traffic.
 *     atGrade      true for a link road on the ground at a ramp foot that the
 *                  map data lacks: drawn as a plain strip of road with no
 *                  parapets, piers or collision.
 *     mainSpan     [from, to, spans]: the stretch over a river, in metres
 *                  along the chain, bank to bank. Piers stand at its ends and
 *                  at equal spans between (on pile caps, never slid aside),
 *                  the girder deepens by `haunch` over each of them, and the
 *                  approach piers step outward from it at pierSpacing. Bake
 *                  it from the map's water polygon; nothing is detected live.
 *
 * Chains of one structure may overlap or touch: a parapet is left out wherever
 * it would stand on a sibling chain's deck at the same level, so a ramp
 * leaving the main line (or two close carriageways) reads as one widening deck
 * that splits apart cleanly. A ramp should therefore hold the main deck's
 * level until the two are apart in plan, and only then start to drop. Where
 * a ramp climbs or falls right beside another deck instead (OSM draws some
 * only 5 m apart), its inner points are nudged a metre or two outward so the
 * two decks do not overlap in plan while their levels differ.
 * Keep decks at least 5 m apart in height where they cross (MRT Line 6 is at
 * 18 m, the Kuril ramps at 8 and 15 m). No pier is stood on a lower deck.
 *
 * The river bridges are the exception to "never join two carriageways": OSM
 * draws each as two one-way lines 8 to 15 m apart, but each is one deck, so
 * its chain is the midline of the pair and the deck is the full width.
 *
 * The first three structures below were generated from OSM bridge ways (layer 1, 2,
 * 3 taken as 8, 15, 22 m; every height is inferred, none surveyed).
 */
