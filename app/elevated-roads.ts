/** A deck cross-section: `rx, rz` point right of travel, stretched to mitre the bend. */
export type ElevatedRing = {
  x: number;
  z: number;
  s: number;
  top: number;
  rx: number;
  rz: number;
  /** Girder depth below the road surface here. */
  depth: number;
  /** Whether the left and right parapets stand here (false over a sibling deck). */
  parapet: [boolean, boolean];
};

export type ElevatedChainLayout = {
  /** World [x, z] centreline. */
  plan: MetroPoint[];
  length: number;
  /** Half the deck width, parapets included. */
  half: number;
  /** Lanes across the deck. */
  lanes: number;
  atGrade: boolean;
  /** Two-way traffic (see the chain's `twoWay`). */
  twoWay: boolean;
  /**
   * Height added to the road surface so that overlapping chains (of any
   * structure) never share a plane: a few centimetres, different for every
   * pair of chains that overlap at one level.
   */
  lift: number;
  rings: ElevatedRing[];
  /** Girder depth below the road surface at a distance along the chain. */
  depthAt: (s: number) => number;
  /** Where piers stand; `river` ones are the main span's, on pile caps. */
  pierStations: Array<{ s: number; river: boolean }>;
  /** Position, unit tangent and road surface height at a distance along the chain. */
  at: (s: number) => { x: number; z: number; tx: number; tz: number; top: number };
  /** Plan distance from a point to the centreline, and where along it that is. */
  nearest: (x: number, z: number) => { distance: number; s: number };
};

export type ElevatedRoadLayout = { road: ElevatedRoad; chains: ElevatedChainLayout[] };

/** Longest stretch of deck between two cross-sections, in metres. */
const MAX_RING_SPACING = 60;

function nearestOnPlan(plan: MetroPoint[], distances: number[], x: number, z: number) {
  let best = Infinity;
  let bestS = 0;
  for (let index = 1; index < plan.length; index++) {
    const [ax, az] = plan[index - 1];
    const [bx, bz] = plan[index];
    const dx = bx - ax;
    const dz = bz - az;
    const lengthSquared = dx * dx + dz * dz || 1;
    const t = Math.min(1, Math.max(0, ((x - ax) * dx + (z - az) * dz) / lengthSquared));
    const distanceSquared = (x - ax - dx * t) ** 2 + (z - az - dz * t) ** 2;
    if (distanceSquared < best) {
      best = distanceSquared;
      bestS = distances[index - 1] + Math.sqrt(lengthSquared) * t;
    }
  }
  return { distance: Math.sqrt(best), s: bestS };
}

/** Project the table into world metres and work out every deck cross-section. */
export function layoutElevatedRoads(
  toWorld: (lat: number, lon: number) => MetroPoint,
  roads: ElevatedRoad[] = ELEVATED_ROADS,
): ElevatedRoadLayout[] {
  const layouts = roads.map((road) => {
    const drafts = road.chains.map((chain) => {
      const plan = chain.points.map(([lat, lon]) => toWorld(lat, lon));
      const distances = [0];
      for (let index = 1; index < plan.length; index++) {
        distances.push(distances[index - 1] + Math.hypot(plan[index][0] - plan[index - 1][0], plan[index][1] - plan[index - 1][1]));
      }
      const length = distances[distances.length - 1];
      const keys = chain.heights
        .map(([distance, top]) => [distance === Infinity ? length : distance < 0 ? length + distance : distance, top] as [number, number])
        .sort((a, b) => a[0] - b[0]);
      const heightAt = (s: number) => {
        if (s <= keys[0][0]) return keys[0][1];
        for (let index = 1; index < keys.length; index++) {
          const [s0, h0] = keys[index - 1];
          const [s1, h1] = keys[index];
          if (s <= s1) {
            const t = (s - s0) / Math.max(s1 - s0, 1e-6);
            return h0 + (h1 - h0) * t;
          }
        }
        return keys[keys.length - 1][1];
      };
      const at = (s: number) => {
        const clamped = Math.min(length, Math.max(0, s));
        let low = 1;
        let high = plan.length - 1;
        while (low < high) {
          const middle = (low + high) >> 1;
          if (distances[middle] < clamped) low = middle + 1;
          else high = middle;
        }
        const [ax, az] = plan[low - 1];
        const [bx, bz] = plan[low];
        const span = Math.max(distances[low] - distances[low - 1], 1e-6);
        const t = (clamped - distances[low - 1]) / span;
        return { x: ax + (bx - ax) * t, z: az + (bz - az) * t, tx: (bx - ax) / span, tz: (bz - az) / span, top: heightAt(clamped) };
      };
      // Cross-sections at every plan vertex and height key (grades are straight
      // between keys), and never further apart than MAX_RING_SPACING.
      const stops = [...distances, ...keys.map(([s]) => s).filter((s) => s > 0 && s < length)];
      // The main span: a haunched girder, deepest over each pier and for half
      // a span out over the banks, and the piers that carry it.
      const span = chain.atGrade ? undefined : chain.mainSpan;
      const haunch = road.haunch ?? 0;
      const spanLength = span ? (span[1] - span[0]) / span[2] : 0;
      const depthAt = (s: number) => {
        if (!span || haunch === 0) return road.depth;
        // 0 over a pier, 1 at mid-span and beyond.
        const fromPier = s < span[0] ? (span[0] - s) / (spanLength / 2)
          : s > span[1] ? (s - span[1]) / (spanLength / 2)
            : 1 - Math.abs(2 * (((s - span[0]) / spanLength) % 1) - 1);
        return road.depth + haunch * (1 - Math.min(1, fromPier)) ** 2;
      };
      const pierStations: Array<{ s: number; river: boolean }> = [];
      if (span) {
        for (let index = 0; index <= span[2]; index++) pierStations.push({ s: span[0] + index * spanLength, river: true });
        for (let s = span[0] - road.pierSpacing; s > road.pierSpacing / 3; s -= road.pierSpacing) pierStations.push({ s, river: false });
        for (let s = span[1] + road.pierSpacing; s < length - road.pierSpacing / 3; s += road.pierSpacing) pierStations.push({ s, river: false });
        if (haunch > 0) {
          for (let s = span[0] - spanLength / 2; s <= span[1] + spanLength / 2 + 0.01; s += spanLength / 8) {
            if (s > 0 && s < length) stops.push(s);
          }
        }
      } else if (!chain.atGrade) {
        for (let s = road.pierSpacing / 2; s < length; s += road.pierSpacing) pierStations.push({ s, river: false });
      }
      stops.sort((a, b) => a - b);
      const ringStops: number[] = [];
      for (const s of stops) {
        const previous = ringStops[ringStops.length - 1];
        if (previous !== undefined && s - previous < 0.75) continue;
        if (previous !== undefined && s - previous > MAX_RING_SPACING) {
          const steps = Math.ceil((s - previous) / MAX_RING_SPACING);
          for (let step = 1; step < steps; step++) ringStops.push(previous + ((s - previous) * step) / steps);
        }
        ringStops.push(s);
      }
      const centres = ringStops.map((s) => ({ s, ...at(s) }));
      const rings: ElevatedRing[] = centres.map((centre, index) => {
        const before = centres[Math.max(0, index - 1)];
        const after = centres[Math.min(centres.length - 1, index + 1)];
        let inX = centre.x - before.x;
        let inZ = centre.z - before.z;
        let outX = after.x - centre.x;
        let outZ = after.z - centre.z;
        if (index === 0) [inX, inZ] = [outX, outZ];
        if (index === centres.length - 1) [outX, outZ] = [inX, inZ];
        const inLength = Math.hypot(inX, inZ) || 1;
        const outLength = Math.hypot(outX, outZ) || 1;
        let mx = inX / inLength + outX / outLength;
        let mz = inZ / inLength + outZ / outLength;
        const mitreLength = Math.hypot(mx, mz) || 1;
        mx /= mitreLength;
        mz /= mitreLength;
        // Widen the section at a bend so the deck keeps its width either side.
        const stretch = 1 / Math.max(0.7, (mx * inX + mz * inZ) / inLength);
        return { x: centre.x, z: centre.z, s: centre.s, top: centre.top, rx: -mz * stretch, rz: mx * stretch, depth: depthAt(centre.s), parapet: [true, true] };
      });
      let minX = Infinity;
      let maxX = -Infinity;
      let minZ = Infinity;
      let maxZ = -Infinity;
      for (const [x, z] of plan) {
        minX = Math.min(minX, x);
        maxX = Math.max(maxX, x);
        minZ = Math.min(minZ, z);
        maxZ = Math.max(maxZ, z);
      }
      const half = chain.halfWidth ?? road.deckHalfWidth;
      const nearest = (x: number, z: number) => (
        x < minX - 40 || x > maxX + 40 || z < minZ - 40 || z > maxZ + 40
          ? { distance: Infinity, s: 0 }
          : nearestOnPlan(plan, distances, x, z)
      );
      return { plan, length, half, lanes: chain.lanes ?? road.lanes ?? 2, atGrade: chain.atGrade === true, twoWay: chain.twoWay === true, lift: 0, rings, depthAt, pierStations, at, nearest };
    });
    return { road, chains: drafts };
  });
  // Parapets and surface lifts are worked out across every structure, so a
  // ramp of one entry that starts on another's deck (the expressway ramps on
  // the Tejgaon Link Flyover) opens its parapets there too.
  const drafts = layouts.flatMap((layout) => layout.chains);
  drafts.forEach((draft, draftIndex) => {
    const touching = new Set<number>();
    for (const ring of draft.rings) {
      for (const side of [0, 1] as const) {
        // A parapet that would stand on a sibling chain's deck is left out.
        const reach = (side === 0 ? -1 : 1) * (draft.half - 0.25);
        const edgeX = ring.x + ring.rx * reach;
        const edgeZ = ring.z + ring.rz * reach;
        ring.parapet[side] = !draft.atGrade && !drafts.some((sibling, siblingIndex) => {
          if (siblingIndex === draftIndex) return false;
          const nearest = sibling.nearest(edgeX, edgeZ);
          return nearest.distance < sibling.half - 0.35 && Math.abs(sibling.at(nearest.s).top - ring.top) < 1.2;
        });
      }
      // Earlier chains whose road surface this one overlaps at one level.
      for (let siblingIndex = 0; siblingIndex < draftIndex; siblingIndex++) {
        if (touching.has(siblingIndex)) continue;
        const sibling = drafts[siblingIndex];
        const nearest = sibling.nearest(ring.x, ring.z);
        if (nearest.distance < sibling.half + draft.half && Math.abs(sibling.at(nearest.s).top - ring.top) < 1.2) touching.add(siblingIndex);
      }
    }
    let level = 0;
    const taken = new Set([...touching].map((siblingIndex) => drafts[siblingIndex].lift));
    while (taken.has(level * 0.04)) level++;
    draft.lift = level * 0.04;
  });
  return layouts;
}

/**
 * Whether another chain (of any structure) lies under a point of `self` at
 * `below` metres up: where a pier must not stand. A deck within a metre of
 * `below` is a sibling merging at the same level and does not count, and nor
 * does a link road on the ground that runs along under the deck (within about
 * 35° of the unit tangent `tx, tz`) rather than across it: piers stand in it
 * as they do in the median of a street.
 */
export function elevatedDeckBelow(
  layouts: ElevatedRoadLayout[],
  self: ElevatedChainLayout,
  x: number,
  z: number,
  tx: number,
  tz: number,
  below: number,
  margin: number,
) {
  return layouts.some(({ chains }) => chains.some((chain) => {
    if (chain === self) return false;
    const nearest = chain.nearest(x, z);
    if (nearest.distance >= chain.half + margin) return false;
    const under = chain.at(nearest.s);
    if (under.top >= below - 1) return false;
    return !chain.atGrade || Math.abs(under.tx * tx + under.tz * tz) < 0.82;
  }));
}

/**
 * The stretches of a way in `trimsWayIds` that still lie on the ground: the
 * way with whatever runs under one of the structure's decks cut out. Cut by
 * geometry, so it holds for any version of the way's points.
 */
export function groundRunsOfTrimmedWay(layout: ElevatedRoadLayout, points: MetroPoint[]): MetroPoint[][] {
  const under = (x: number, z: number) => layout.chains.some((chain) => {
    if (chain.atGrade) return false;
    const nearest = chain.nearest(x, z);
    return nearest.distance < chain.half + 2 && nearest.s > 0.01 && nearest.s < chain.length - 0.01;
  });
  const runs: MetroPoint[][] = [];
  let run: MetroPoint[] = [];
  const close = () => {
    if (run.length >= 2) runs.push(run);
    run = [];
  };
  for (let index = 0; index < points.length; index++) {
    const [bx, bz] = points[index];
    if (index === 0) {
      if (!under(bx, bz)) run.push([bx, bz]);
      continue;
    }
    const [ax, az] = points[index - 1];
    const steps = Math.max(1, Math.ceil(Math.hypot(bx - ax, bz - az) / 4));
    let wasUnder = under(ax, az);
    for (let step = 1; step <= steps; step++) {
      const t = step / steps;
      const isUnder = under(ax + (bx - ax) * t, az + (bz - az) * t);
      if (isUnder !== wasUnder) {
        // Close in on where the way passes the edge of the deck.
        let low = (step - 1) / steps;
        let high = t;
        for (let pass = 0; pass < 6; pass++) {
          const middle = (low + high) / 2;
          if (under(ax + (bx - ax) * middle, az + (bz - az) * middle) === wasUnder) low = middle;
          else high = middle;
        }
        const cut = wasUnder ? high : low;
        run.push([ax + (bx - ax) * cut, az + (bz - az) * cut]);
        if (isUnder) close();
        wasUnder = isUnder;
      }
    }
    if (!wasUnder) run.push([bx, bz]);
  }
  close();
  return runs;
}

function distanceToSegmentSquared(px: number, pz: number, x1: number, z1: number, x2: number, z2: number) {
  const dx = x2 - x1;
  const dz = z2 - z1;
  const lengthSquared = dx * dx + dz * dz;
  const t = lengthSquared === 0 ? 0 : Math.min(1, Math.max(0, ((px - x1) * dx + (pz - z1) * dz) / lengthSquared));
  return (px - x1 - dx * t) ** 2 + (pz - z1 - dz * t) ** 2;
}

function segmentsCross(ax: number, az: number, bx: number, bz: number, cx: number, cz: number, dx: number, dz: number) {
  const side = (px: number, pz: number, qx: number, qz: number, rx: number, rz: number) => (qx - px) * (rz - pz) - (qz - pz) * (rx - px);
  const d1 = side(ax, az, bx, bz, cx, cz);
  const d2 = side(ax, az, bx, bz, dx, dz);
  const d3 = side(cx, cz, dx, dz, ax, az);
  const d4 = side(cx, cz, dx, dz, bx, bz);
  return ((d1 > 0 && d2 < 0) || (d1 < 0 && d2 > 0)) && ((d3 > 0 && d4 < 0) || (d3 < 0 && d4 > 0));
}

function pointInPolygon(x: number, z: number, points: MetroPoint[]) {
  let inside = false;
  for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
    const [xi, zi] = points[i];
    const [xj, zj] = points[j];
    if (((zi > z) !== (zj > z)) && (x < ((xj - xi) * (z - zi)) / (zj - zi || 1e-6) + xi)) inside = !inside;
  }
  return inside;
}

/**
 * Clearance index over every elevated road so procedural buildings, OSM
 * building extrusions and trees keep off the decks and their piers: one grid
 * of centreline pieces, each cleared to its chain's half width plus 2 m. It
 * answers the same two questions as the metro corridor index.
 */
export function buildElevatedRoadCorridor(layouts: ElevatedRoadLayout[]): MetroCorridorIndex {
  const CELL = 120;
  // Pieces are filed in every cell within PAD of them; no clearance exceeds it.
  const PAD = 16;
  type Piece = { x1: number; z1: number; x2: number; z2: number; clearance: number };
  const grid = new Map<number, Piece[]>();
  const cellKey = (cellX: number, cellZ: number) => (cellX + 4096) * 8192 + cellZ + 4096;
  for (const { chains } of layouts) {
    for (const chain of chains) {
      const clearance = Math.min(PAD - 0.5, chain.half + 2);
      for (let index = 1; index < chain.plan.length; index++) {
        const [ax, az] = chain.plan[index - 1];
        const [bx, bz] = chain.plan[index];
        // Short pieces, so a long diagonal span is not filed in a whole block of cells.
        const steps = Math.max(1, Math.ceil(Math.hypot(bx - ax, bz - az) / CELL));
        for (let step = 0; step < steps; step++) {
          const piece: Piece = {
            x1: ax + ((bx - ax) * step) / steps,
            z1: az + ((bz - az) * step) / steps,
            x2: ax + ((bx - ax) * (step + 1)) / steps,
            z2: az + ((bz - az) * (step + 1)) / steps,
            clearance,
          };
          const endX = Math.floor((Math.max(piece.x1, piece.x2) + PAD) / CELL);
          const endZ = Math.floor((Math.max(piece.z1, piece.z2) + PAD) / CELL);
          for (let cellX = Math.floor((Math.min(piece.x1, piece.x2) - PAD) / CELL); cellX <= endX; cellX++) {
            for (let cellZ = Math.floor((Math.min(piece.z1, piece.z2) - PAD) / CELL); cellZ <= endZ; cellZ++) {
              const key = cellKey(cellX, cellZ);
              const bucket = grid.get(key);
              if (bucket) bucket.push(piece);
              else grid.set(key, [piece]);
            }
          }
        }
      }
    }
  }
  return {
    blocksCircle: (x, z, radius) => {
      const endX = Math.floor((x + radius) / CELL);
      const endZ = Math.floor((z + radius) / CELL);
      for (let cellX = Math.floor((x - radius) / CELL); cellX <= endX; cellX++) {
        for (let cellZ = Math.floor((z - radius) / CELL); cellZ <= endZ; cellZ++) {
          const pieces = grid.get(cellKey(cellX, cellZ));
          if (!pieces) continue;
          for (const piece of pieces) {
            if (distanceToSegmentSquared(x, z, piece.x1, piece.z1, piece.x2, piece.z2) < (radius + piece.clearance) ** 2) return true;
          }
        }
      }
      return false;
    },
    blocksPolygon: (points) => {
      if (points.length < 3) return false;
      let minX = Infinity;
      let maxX = -Infinity;
      let minZ = Infinity;
      let maxZ = -Infinity;
      for (const [x, z] of points) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (z < minZ) minZ = z;
        if (z > maxZ) maxZ = z;
      }
      const endX = Math.floor(maxX / CELL);
      const endZ = Math.floor(maxZ / CELL);
      for (let cellX = Math.floor(minX / CELL); cellX <= endX; cellX++) {
        for (let cellZ = Math.floor(minZ / CELL); cellZ <= endZ; cellZ++) {
          const pieces = grid.get(cellKey(cellX, cellZ));
          if (!pieces) continue;
          for (const piece of pieces) {
            // An OSM footprint is cleared a metre closer than a procedural plot.
            const reach = piece.clearance - 1;
            if (
              Math.max(piece.x1, piece.x2) < minX - reach || Math.min(piece.x1, piece.x2) > maxX + reach
              || Math.max(piece.z1, piece.z2) < minZ - reach || Math.min(piece.z1, piece.z2) > maxZ + reach
            ) continue;
            if (pointInPolygon(piece.x1, piece.z1, points) || pointInPolygon(piece.x2, piece.z2, points)) return true;
            for (let index = 0; index < points.length; index++) {
              const [px, pz] = points[index];
              const [qx, qz] = points[(index + 1) % points.length];
              if (
                segmentsCross(piece.x1, piece.z1, piece.x2, piece.z2, px, pz, qx, qz)
                || distanceToSegmentSquared(px, pz, piece.x1, piece.z1, piece.x2, piece.z2) < reach * reach
                || distanceToSegmentSquared(piece.x1, piece.z1, px, pz, qx, qz) < reach * reach
                || distanceToSegmentSquared(piece.x2, piece.z2, px, pz, qx, qz) < reach * reach
              ) return true;
            }
          }
        }
      }
      return false;
    },
  };
}
